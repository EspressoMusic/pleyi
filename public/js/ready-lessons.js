    const text = String(speak || "").trim();
    if (!text) return "";
    return `<button type="button" class="lp-speak-btn" data-say="${escAttr(text)}" aria-label="השמע באנגלית: ${escAttr(text)}">${LP_SPEAKER_ICON}</button>`;
