  /* ---------- building blocks ---------- */

  // The right answer and up to `n` wrong ones: the first of `wrong` that
  // differ from it and from each other.
  function withWrong(answer, wrong, n = 3) {
    const out = [String(answer)];
    wrong.forEach((w) => {
      const s = String(w);
      if (out.length <= n && !out.includes(s)) out.push(s);
    });
    return out;
  }

