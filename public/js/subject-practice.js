    rows.map(([text, math, options, fig]) => ({
      text,
      ...(math && { math }),
      options: options.map(String),
      answer: String(options[0]),
      ...(fig && { fig }),
    }));
  const T = (rows) => rows.map(([text, math, correct, fix, fig]) => ({ text, ...(math && { math }), correct, ...(fix && { fix }), ...(fig && { fig }) }));
  const W = (rows) =>
    rows.map(([text, math, answer, accept, fig]) => ({ text, ...(math && { math }), answer: String(answer), ...(accept && { accept }), ...(fig && { fig }) }));

