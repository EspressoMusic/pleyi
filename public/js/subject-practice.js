/* The school subjects' learning areas — like the Learn English page: a path
   of topics in level order, and in each topic its short lessons
   (subject-lessons.js) and practice exercises. services/subject.html reads
   the subject from its address (/services/math …) and runs
   english-learning.js on it (window.LEARN_SUBJECT).

   Area: { title, hero, path: [{ title, topics: [ids] }], topics }
   Topic: { id, title, lessons: [lesson ids], exercises }
   - Every topic opens with a matching exercise made of its lessons' words
     (vocab), then its own exercises; the topic page lists them by level (1–3).
   - Questions are written as short rows:
       C [text, math, options, fig?]  — the first option is the right one (the
                                        runner shuffles them).
       T [text, math, correct, fix?, fig?]
       W [text, math, answer, accept?, fig?]
     text: Hebrew; "$...$" is a math bit and {a|b} a fraction, as in the
     lessons. math: a big math line under the text, where "___" is the place
     of the answer. fig: a drawing from lesson-figures.js ({ kind, ... }).
   - Most math questions come out of small loops, so their answers are
     computed, not typed.
   No girls' names, pictures or sentences about girls; boys' names only. */
