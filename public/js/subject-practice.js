  const TRUE_FALSE = "קראו ובחרו: נכון או לא נכון.";
  const CHECK_SUM = "בדקו את התרגיל ובחרו: נכון או לא נכון.";
  const TYPE = "כתבו את התשובה ולחצו על „בדיקה”.";

  const exercise = (type) => (id, title, instructions, level, questions) => ({ id, type, title, instructions, level, roundSize: 10, questions });
  const choice = exercise("choice");
  const truefalse = exercise("truefalse");
  const write = exercise("write");

  // The topic's words as a matching board: a word and what it means.
  function wordsMatch(lessonTopic) {
    const terms = new Set();
    const meanings = new Set();
    const pairs = [];
    LESSONS.filter((l) => l.topic === lessonTopic).forEach((l) =>
      l.vocab.forEach(([a, b]) => {
        if (terms.has(a) || meanings.has(b)) return;
        terms.add(a);
        meanings.add(b);
        pairs.push({ a, b });
      })
    );
    return { id: "words", type: "match", title: "מילים חשובות – התאמה", instructions: "לחצו על מילה ואז על ההסבר שלה.", level: 1, boardSize: 6, pairs };
  }

  // `lessonTopic`: the lessons' topic in subject-lessons.js, when the id here
  // is different.
  function topic(id, title, exercises, lessonTopic = id) {
    return {
      id,
      title,
      lessons: LESSONS.filter((l) => l.topic === lessonTopic).map((l) => l.id),
      exercises: [wordsMatch(lessonTopic), ...exercises],
    };
  }

