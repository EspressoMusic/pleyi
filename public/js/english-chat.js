  // A conversation as an exercise of its topic. Its questions keep their
  // order (english-learning.js plays them as one conversation).
  function exerciseOf(chat) {
    return {
      id: chat.id,
      type: "chat",
      level: chat.level,
      scene: chat.scene,
      sceneEn: chat.sceneEn,
      title: `שיחה: ${chat.scene}`,
      titleEn: `Chat: ${chat.sceneEn}`,
      instructions: `${chat.role} בחרו מה לענות לו.`,
      instructionsEn: `${chat.roleEn} Choose what to answer.`,
      // Built here, not by the server, so it has no "new exercises".
      derived: true,
      questions: chat.turns.map(([text, he, options, replyHe]) => ({ text, he, options, answer: options[0], replyHe })),
    };
  }

  const list = [];
  CHATS.forEach((chat) => {
    const topic = TOPICS.find((tp) => tp.id === chat.topic);
    if (!topic) return;
    topic.exercises = topic.exercises || [];
    if (topic.exercises.some((ex) => ex.id === chat.id)) return;
    const exercise = exerciseOf(chat);
    topic.exercises.push(exercise);
    list.push({ topic, exercise });
  });

  // Every conversation with its topic, in the order above (by level).
  window.ENGLISH_CHATS = list;
